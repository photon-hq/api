"""Generate the Go client (packages/go) from openapi/sdk.json and openapi/rpc-manifest.json.

Writes config_generated.go, models_generated.go and operations_generated.go.
`--check` compares instead of writing. Standard library only; needs `gofmt`.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "openapi/sdk.json"
MANIFEST = ROOT / "openapi/rpc-manifest.json"
CONFIG = ROOT / "config/sdk.json"
OUT = ROOT / "packages/go"
PACKAGE_DIR = OUT
PREFIX = "#/components/schemas/"
HEADER = "// Code generated by tools/go-codegen from openapi/sdk.json. DO NOT EDIT.\n\npackage photonapi\n\n"

INITIALISMS = {"id": "ID", "url": "URL", "uri": "URI", "uuid": "UUID", "ip": "IP", "http": "HTTP", "api": "API", "sso": "SSO", "sms": "SMS"}

spec = json.loads(SPEC.read_text())
SCHEMAS = spec["components"]["schemas"]
MANIFEST_OPS = json.loads(MANIFEST.read_text())["operations"]


def words(name: str) -> list[str]:
    parts = re.split(r"[^0-9A-Za-z]+", name)
    out: list[str] = []
    for part in parts:
        out += re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+", part)
    return out


def handwritten_identifiers() -> set[str]:
    """Exported top-level names of the hand-written files, which no schema may take."""
    found: set[str] = set()
    for path in PACKAGE_DIR.glob("*.go"):
        if path.name.endswith(("_generated.go", "_test.go")):
            continue
        found.update(re.findall(r"^(?:type|func|const|var) ([A-Z]\w*)", path.read_text(), re.M))
    return found


def ident(name: str) -> str:
    """Exported Go identifier for methods, service fields and constant suffixes."""
    result = "".join(w[:1].upper() + w[1:] for w in words(name))
    if not result or result[0].isdigit():
        return "X" + result
    return result


def type_name(name: str) -> str:
    """Go type name of a schema, kept clear of the hand-written identifiers."""
    result = ident(name)
    return result + "Model" if result in HANDWRITTEN else result


HANDWRITTEN = handwritten_identifiers()


def field_name(name: str) -> str:
    result = "".join(INITIALISMS.get(w.lower(), w[:1].upper() + w[1:]) for w in words(name))
    return "X" + result if not result or result[0].isdigit() else result


def doc(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    lines = [line.rstrip() for line in text.strip().splitlines()]
    return "".join(f"{indent}// {line}\n" if line else f"{indent}//\n" for line in lines)


def ref_name(schema: dict) -> str | None:
    ref = schema.get("$ref")
    return ref[len(PREFIX):] if ref and ref.startswith(PREFIX) else None


# -- schema classification ----------------------------------------------------------------

NULL = {"type": "null"}


def is_null(schema: dict) -> bool:
    return schema.get("type") == "null"


def nullable_inner(schema: dict) -> tuple[dict, bool]:
    """Strip null from `type: [x, null]` and `anyOf: [x, null]`."""
    t = schema.get("type")
    if isinstance(t, list):
        rest = [x for x in t if x != "null"]
        if len(rest) == 1:
            return {**schema, "type": rest[0]}, "null" in t
        return schema, False
    members = schema.get("anyOf") or schema.get("oneOf")
    if members and any(is_null(m) for m in members):
        rest = [m for m in members if not is_null(m)]
        if len(rest) == 1:
            return rest[0], True
    return schema, False


def union_members(schema: dict) -> list[dict] | None:
    members = schema.get("oneOf") or schema.get("anyOf")
    return members if members and len(members) > 0 else None


class Mapper:
    """Maps schemas to Go types. `kind` of a named schema decides nilability."""

    def __init__(self) -> None:
        self.kinds: dict[str, str] = {}
        self.needed: dict[str, None] = {}
        # Inline objects hoisted into named structs: Go name -> schema, and those not yet emitted.
        self.hoisted: dict[str, dict] = {}
        self.pending: list[str] = []

    def kind(self, name: str) -> str:
        if name in self.kinds:
            return self.kinds[name]
        self.kinds[name] = "struct"  # recursion guard
        self.kinds[name] = self._kind(SCHEMAS[name])
        return self.kinds[name]

    def _kind(self, s: dict) -> str:
        inner, _ = nullable_inner(s)
        if (r := ref_name(inner)):
            return self.kind(r)
        if "allOf" in inner:
            return "struct"
        if union_members(inner):
            members = union_members(inner)
            if len(members) == 1 and ref_name(members[0]):
                return self.kind(ref_name(members[0]))
            if self.is_string_union(members):
                return "string"
            return "union" if self.is_object_union(members) else "any"
        t = inner.get("type")
        if "enum" in inner or "const" in inner:
            return "string" if t == "string" or t is None else "scalar"
        if t == "object":
            return "struct" if inner.get("properties") else "map"
        if t == "array":
            return "slice"
        if t in ("string", "number", "integer", "boolean"):
            return "scalar"
        return "any"

    def is_string_union(self, members: list[dict]) -> bool:
        """Every member is a plain string (or refers to one)."""
        for m in members:
            m, _ = nullable_inner(m)
            if (r := ref_name(m)):
                if self.kind(r) != "string":
                    return False
            elif m.get("type") != "string":
                return False
        return True

    def is_object_union(self, members: list[dict]) -> bool:
        """Every member is a schema reference or an object."""
        return all(ref_name(m) or m.get("type") == "object" or "properties" in m or "allOf" in m for m in members)

    def go_type(self, s: dict, plain_time: bool = False, hint: str | None = None) -> tuple[str, bool]:
        """Return (Go type, nilable). `hint` names the struct an inline object is hoisted into."""
        inner, _ = nullable_inner(s)
        if (r := ref_name(inner)):
            self.need(r)
            return type_name(r), self.kind(r) in ("map", "slice", "any")
        members = union_members(inner)
        if "allOf" in inner or (inner.get("type") == "object" and inner.get("properties") and not members):
            return self.hoist(hint, inner), False
        if members:
            if len(members) == 1:
                return self.go_type(members[0], plain_time, hint)
            if self.is_string_union(members):
                return "string", False
            if self.is_object_union(members):
                return "Union", False
            return "any", True
        t = inner.get("type")
        if inner.get("format") == "binary":
            return "[]byte", True
        if t == "string" or (("enum" in inner or "const" in inner) and t in (None, "string")):
            if inner.get("format") == "date-time" and not plain_time:
                return "Timestamp", False
            return "string", False
        if t == "integer":
            return "int64", False
        if t == "number":
            return "float64", False
        if t == "boolean":
            return "bool", False
        if t == "array":
            items = inner.get("items")
            if items:
                return "[]" + self.element(items, plain_time, hint and hint + "Item"), True
            return "[]any", True
        if t == "object":
            extra = inner.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return "map[string]" + self.element(extra, plain_time, hint and hint + "Value"), True
            return "map[string]any", True
        return "any", True

    def element(self, s: dict, plain_time: bool, hint: str | None) -> str:
        """Go type of an array item or map value; a nullable one is a pointer, so null survives a round trip."""
        typ, nilable = self.go_type(s, plain_time, hint)
        return "*" + typ if nullable_inner(s)[1] and not nilable else typ

    def hoist(self, name: str | None, schema: dict) -> str:
        """Name an inline object (or `allOf`) as its own struct, emitted by `drain`."""
        if name is None:
            sys.exit(f"inline object without a type name: {json.dumps(schema)[:200]}")
        if name in self.hoisted:
            if self.hoisted[name] != schema:
                sys.exit(f"inline object type {name} collides with another inline object")
            return name
        self.hoisted[name] = schema
        self.pending.append(name)
        return name

    def need(self, name: str) -> None:
        if name not in self.needed:
            self.needed[name] = None


mapper = Mapper()


def collect(schema: dict) -> None:
    """Mark every named schema reachable from `schema`."""
    if (r := ref_name(schema)):
        visit(r)
        return
    for key in ("allOf", "oneOf", "anyOf", "prefixItems"):
        for m in schema.get(key) or []:
            collect(m)
    for p in (schema.get("properties") or {}).values():
        collect(p)
    for key in ("items", "additionalProperties"):
        if isinstance(schema.get(key), dict):
            collect(schema[key])


visited: set[str] = set()


def visit(name: str) -> None:
    if name in visited:
        return
    visited.add(name)
    mapper.need(name)
    collect(SCHEMAS[name])


# -- models -------------------------------------------------------------------------------


def merged_object(schema: dict) -> tuple[dict, set[str]]:
    """Flatten `allOf` into one property map and required set."""
    props: dict = {}
    required: set[str] = set()
    for key in ("allOf",):
        for member in schema.get(key) or []:
            target = SCHEMAS[ref_name(member)] if ref_name(member) else member
            p, r = merged_object(target)
            props.update(p)
            required |= r
    props.update(schema.get("properties") or {})
    required |= set(schema.get("required") or [])
    return props, required


def is_absent(p: dict) -> bool:
    return p.get("not") == {}


def struct_fields(schema: dict, owner: str) -> str:
    props, required = merged_object(schema)
    out = ""
    used: set[str] = set()
    for pname, p in props.items():
        if is_absent(p):
            continue
        inner, nullable = nullable_inner(p)
        optional = pname not in required
        field = field_name(pname)
        while field in used:
            field += "_"
        used.add(field)
        typ, nilable = mapper.go_type(p, hint=owner + field)
        tag = pname
        if optional and nullable:
            # Three states: absent, explicit null (clears the field), value.
            typ = f"Nullable[{typ}]"
            tag += ",omitzero"
        elif optional or nullable:
            if not nilable:
                typ = "*" + typ
            tag += ",omitempty" if optional else ""
        out += doc(inner.get("description"), "\t")
        out += f'\t{field} {typ} `json:"{tag}"`\n'
    return out


def emit_struct(go: str, schema: dict) -> str:
    out = doc(schema.get("description") or schema.get("title"))
    return out + f"type {go} struct {{\n{struct_fields(schema, go)}}}\n\n"


def drain() -> str:
    """Emit the hoisted inline objects not yet emitted, after the model that reached them."""
    out = ""
    while mapper.pending:
        name = mapper.pending.pop(0)
        out += emit_struct(name, mapper.hoisted[name])
    return out


def emit_model(name: str) -> str:
    s = SCHEMAS[name]
    go = type_name(name)
    kind = mapper.kind(name)
    inner, nullable = nullable_inner(s)
    d = doc(s.get("description") or s.get("title"))
    if kind == "struct" and not (ref_name(inner) or (union_members(inner) and not "allOf" in inner)):
        return emit_struct(go, inner)
    if ref_name(inner):
        return d + f"type {go} = {type_name(ref_name(inner))}\n\n"
    members = union_members(inner)
    if members and len(members) == 1:
        typ, _ = mapper.go_type(members[0], hint=go + "Member")
        return d + f"type {go} = {typ}\n\n"
    if kind == "union":
        ext = inner.get("x-photon-extension") or {}
        out = d + f"type {go} struct{{ Union }}\n\n"
        disc = ext.get("discriminator")
        if disc:
            out += f'// Kind returns the "{disc}" discriminator, or "" when absent.\nfunc (u {go}) Kind() string {{ return u.Discriminator("{disc}") }}\n\n'
        for m in members:
            if not ref_name(m):
                continue
            mn = type_name(ref_name(m))
            out += f"// As{mn} decodes the value as {mn}.\nfunc (u {go}) As{mn}() ({mn}, error) {{ return UnionAs[{mn}](u.Union) }}\n\n"
        return out
    if kind == "any":
        return d + f"type {go} = any\n\n"
    if "enum" in inner and inner.get("type") in (None, "string"):
        out = d + f"type {go} string\n\nconst (\n"
        seen: set[str] = set()
        for value in inner["enum"]:
            const = go + ident(str(value))
            while const in seen:
                const += "_"
            seen.add(const)
            out += f"\t{const} {go} = {json.dumps(value, ensure_ascii=False)}\n"
        return out + ")\n\n"
    typ, _ = mapper.go_type(inner, hint=go)
    return d + f"type {go} {typ}\n\n"


# -- operations ---------------------------------------------------------------------------


class Node:
    def __init__(self, path: tuple[str, ...]) -> None:
        self.path = path
        self.children: dict[str, "Node"] = {}
        self.ops: list[dict] = []

    @property
    def go(self) -> str:
        return "".join(ident(p) for p in self.path) + "Service"


def build_tree() -> Node:
    root = Node(())
    for op in MANIFEST_OPS:
        node = root
        for i, seg in enumerate(op["namespace"]):
            node = node.children.setdefault(seg, Node(tuple(op["namespace"][: i + 1])))
        node.ops.append(op)
    return root


def media(responses: dict) -> list[tuple[str, str, str | None]]:
    """(status, media type, schema name) for 2xx responses."""
    out = []
    for status, content in responses.items():
        if status[0] == "2":
            if not content:
                out.append((status, "", None))
            for mt, ref in content.items():
                out.append((status, mt, ref[len(PREFIX):] if isinstance(ref, str) and ref else None))
    return out


def param_fields(op: dict) -> list[dict]:
    fields: list[dict] = []
    used: set[str] = set()
    for p in op["parameters"]:
        loc = p["location"]
        name = field_name(p["name"])
        if name in used:
            name = field_name(loc + "-" + p["name"])
        used.add(name)
        if loc == "path":
            typ, nilable = "string", False
        else:
            typ, nilable = mapper.go_type(p["schema"], plain_time=True, hint=f"{ident(op['operationId'])}Params{name}")
        if not p["required"] and not nilable:
            typ = "*" + typ
        fields.append({"p": p, "name": name, "type": typ, "loc": loc})
    return fields


def emit_op(node: Node, op: dict) -> tuple[str, str]:
    """Return (params struct, method)."""
    method_name = ident(op["rpcMethod"])
    op_type = ident(op["operationId"])
    fields = param_fields(op)
    body = op.get("requestBody")
    body_type = None
    raw_body = False
    if body:
        # JSON wins when a body also has a form or protobuf encoding.
        mt, ref = next(((m, r) for m, r in body["content"].items() if m == "application/json"), next(iter(body["content"].items())))
        inline_binary = isinstance(ref, dict) and ref.get("format") == "binary"
        if mt.startswith("multipart/") or inline_binary:
            raw_body, body_type = True, "io.Reader"
        else:
            schema = {"$ref": ref} if isinstance(ref, str) else (ref or {})
            body_type, nilable = mapper.go_type(schema, hint=op_type + "Body")
            if not body["required"] and not nilable:
                body_type = "*" + body_type

    ok = media(op["responses"])
    result = None  # (kind, go type)
    schemas = {(mt, n) for _, mt, n in ok}
    if not ok:
        has_redirect = any(s[0] == "3" for s in op["responses"])
        result = ("redirect", "Redirect") if has_redirect else None
    elif len(schemas) > 1:
        result = ("union", "Union")
    else:
        _, mt, n = ok[0]
        if mt == "":
            result = None
        elif mt == "*/*":
            result = ("binary", "BinaryResponse")
        else:
            typ, _ = mapper.go_type({"$ref": PREFIX + n})
            result = ("json", typ)

    params_name = f"{op_type}Params"
    has_params = bool(fields) or body_type is not None
    structure = ""
    if has_params:
        structure += f"// {params_name} holds the parameters of {method_name}.\ntype {params_name} struct {{\n"
        for f in fields:
            p = f["p"]
            wire = p["wireName"]
            where = {"path": "path", "query": "query", "header": "header"}[f["loc"]]
            note = ""
            if wire.lower() == "idempotency-key":
                note = " Generated when empty."
            structure += doc((p["schema"].get("description") or "").strip(), "\t")
            structure += f"\t// {f['name']} is the {where} parameter {wire}.{note}\n"
            if wire.lower() == "content-length":
                f["type"] = "int64"
            structure += f"\t{f['name']} {f['type']}\n"
        if body_type:
            structure += f"\t// Body is the request body.\n\tBody {body_type}\n"
        structure += "}\n\n"

    ret = f"(*{result[1]}, error)" if result else "error"
    sig_params = f"ctx context.Context, params *{params_name}, " if has_params else "ctx context.Context, "
    d = doc(op.get("summary"))
    if op.get("description") and op.get("description") != op.get("summary"):
        d += "//\n" + doc(op["description"])
    code = d + f"func (s *{node.go}) {method_name}({sig_params}opts ...RequestOption) {ret} {{\n"
    if has_params:
        code += f"\tif params == nil {{\n\t\tparams = &{params_name}{{}}\n\t}}\n"
    code += f'\tspec := newSpec("{op["operationId"]}", "{op["httpMethod"]}", "{op["path"]}")\n'
    if op["safe"]:
        code += "\tspec.safe = true\n"
    if op["idempotencyKeyRequired"]:
        code += "\tspec.idempotent = true\n"
    if result and result[0] == "binary":
        code += '\tspec.accept = "*/*"\n'
    if result and result[0] == "redirect":
        code += "\tspec.redirect = true\n"
    if "304" in op["responses"]:
        code += "\tspec.notModified = true\n"
    for f in fields:
        p, loc = f["p"], f["loc"]
        wire = p["wireName"]
        if loc == "path":
            code += f'\tspec.setPath("{p["wireName"]}", params.{f["name"]})\n'
        elif loc == "query":
            code += f'\tspec.addQuery("{wire}", params.{f["name"]})\n'
        elif wire.lower() == "content-length":
            code += f"\tspec.length = params.{f['name']}\n"
        else:
            code += f'\tspec.setHeader("{wire}", params.{f["name"]})\n'
    if body_type and raw_body:
        code += "\tspec.rawBody = params.Body\n"
    elif body_type:
        code += "\tspec.setJSON(params.Body)\n"
    if result is None:
        code += "\treturn s.c.do(ctx, spec, nil, opts)\n}\n\n"
    else:
        code += f"\tvar out {result[1]}\n\tif err := s.c.do(ctx, spec, &out, opts); err != nil {{\n\t\treturn nil, err\n\t}}\n\treturn &out, nil\n}}\n\n"
    return structure, code


def emit_services(root: Node) -> str:
    params_out: list[str] = []
    out = ""
    nodes: list[Node] = []

    def walk(node: Node) -> None:
        if node.path:
            nodes.append(node)
        for child in node.children.values():
            walk(child)

    walk(root)
    # Client
    out += "// Client calls the Photon API. Build one with NewClient.\ntype Client struct {\n\tc *core\n"
    for name, child in root.children.items():
        out += f"\t{ident(name)} *{child.go}\n"
    out += "}\n\nfunc newClient(c *core) *Client {\n\tclient := &Client{c: c}\n"
    for name, child in root.children.items():
        out += f"\tclient.{ident(name)} = new{child.go}(c)\n"
    out += "\treturn client\n}\n\n"
    for node in nodes:
        out += f"// {node.go} groups the {'.'.join(node.path)} operations.\ntype {node.go} struct {{\n\tc *core\n"
        methods = {ident(op["rpcMethod"]) for op in node.ops}
        for name, child in node.children.items():
            if ident(name) in methods:
                sys.exit(f"{node.go}: method and sub-service both named {ident(name)}")
            out += f"\t{ident(name)} *{child.go}\n"
        out += f"}}\n\nfunc new{node.go}(c *core) *{node.go} {{\n\ts := &{node.go}{{c: c}}\n"
        for name, child in node.children.items():
            out += f"\ts.{ident(name)} = new{child.go}(c)\n"
        out += "\treturn s\n}\n\n"
        for op in node.ops:
            structure, code = emit_op(node, op)
            params_out.append(structure)
            out += code
    return "".join(params_out) + out


def imports(body: str) -> str:
    wanted = [m for m, token in (("context", "context."), ("io", "io.")) if token in body]
    if not wanted:
        return ""
    return "import (\n" + "".join(f'\t"{m}"\n' for m in wanted) + ")\n\n"


def render() -> dict[str, str]:
    for op in MANIFEST_OPS:
        for p in op["parameters"]:
            collect(p["schema"])
        if op.get("requestBody"):
            for ref in op["requestBody"]["content"].values():
                if ref:
                    collect({"$ref": ref} if isinstance(ref, str) else ref)
        for _, _, n in media(op["responses"]):
            if n:
                visit(n)

    services = emit_services(build_tree())

    names = sorted(mapper.needed)
    taken = {type_name(n) for n in names}
    params = {f"{ident(op['operationId'])}Params": op["operationId"] for op in MANIFEST_OPS}
    for params_name, operation_id in params.items():
        if params_name in taken:
            sys.exit(f"params type of {operation_id} collides with a schema")
    models = "".join(emit_model(n) + drain() for n in names) + drain()
    reserved = taken | params.keys() | HANDWRITTEN
    for name in mapper.hoisted:
        if name in reserved:
            sys.exit(f"inline object type {name} collides with a schema, params or hand-written type")

    config = json.loads(CONFIG.read_text())
    files = {
        "config_generated.go": HEADER + f'// DefaultBaseURL is the API origin for the {config["environment"]} contract.\nconst DefaultBaseURL = "{config["defaultBaseUrl"]}"\n',
        "models_generated.go": HEADER + models,
        "operations_generated.go": HEADER + imports(services) + services,
    }
    return {k: gofmt(v) for k, v in files.items()}


def gofmt(source: str) -> str:
    proc = subprocess.run(["gofmt"], input=source, capture_output=True, text=True)
    if proc.returncode:
        sys.exit(f"gofmt failed:\n{proc.stderr}\n--- source head ---\n{source[:3000]}")
    return proc.stdout


def main() -> None:
    files = render()
    if "--check" in sys.argv:
        stale = [n for n, c in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != c]
        if stale:
            sys.exit(f"stale generated Go files: {', '.join(stale)}; run npm run generate:go")
        return
    for name, content in files.items():
        (OUT / name).write_text(content)


if __name__ == "__main__":
    main()
